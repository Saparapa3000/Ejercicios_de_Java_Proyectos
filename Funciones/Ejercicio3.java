public class Ejercicio3 {

    public static int maximo(int a, int b) {
        if (a > b) {
            return a;
        } else {
            return b;
        }
    }

    public static void main(String[] args) {
        System.out.println("El mayor es: " + maximo(8, 15));
    }
}